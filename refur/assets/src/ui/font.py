def glyph(ch: str):
    spec = _RAW.get(ch.upper(), _RAW[" "])
    return spec.split("/")


def text(pix, x, y, msg, color, scale=1, gap=1):
    cx = x
    for ch in msg:
        rows = glyph(ch)
        for ry, row in enumerate(rows):
            for rx, bit in enumerate(row):
                if bit == "1":
                    if scale == 1:
                        pix.set(cx + rx, y + ry, color)
                    else:
                        pix.fill_rect(cx + rx * scale, y + ry * scale, scale, scale, color)
        cx += (5 + gap) * scale
    return cx


def text_width(msg, scale=1, gap=1):
    if not msg:
        return 0
    return (len(msg) * (5 + gap) - gap) * scale


def text_ink(pix, x, y, msg, fill, scale=1, gap=1, shadow=INK):
    """Letters with a 1px shadow down-right, then the fill color."""
    text(pix, x + scale, y + scale, msg, shadow, scale, gap)
    text(pix, x, y, msg, fill, scale, gap)
